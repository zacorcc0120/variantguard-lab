/**
 * Emits src/i18n/en.ts from the English sources.
 *
 * The English dictionary is generated rather than hand-written so it cannot
 * drift from the product: every key is literally the string the code already
 * ships. tests/i18n.test.ts re-derives the key set from source and compares it
 * against this file, so editing a rule's wording without regenerating fails CI.
 *
 * Findings that interpolate live values carry a rule-attached key instead
 * (`finding.<RULE_ID>.<field>[.<n>]`); the value is the English sentence and
 * `{placeholder}` params are resolved against the Risk at render time.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { TERM, UI } from './i18n-ui';
import { PARSE_RATIONALE, PARSE_SUGGESTION, PARSE_SUGGESTION_MOJIBAKE, PARSE_TITLE } from './i18n-parse-extra';

const d = JSON.parse(readFileSync('F:/Temp/vg-dict.json', 'utf8')) as {
  ruleLevel: Record<string, Record<string, string>>;
  findingLevel: Record<string, Record<string, string[]>>;
  parseFindings: Record<string, { message: string; detail?: string }>;
  assumptions: Record<string, Record<string, string>>;
  scenarios: Record<string, Record<string, string>>;
};

/** Single-quoted unless the string needs escaping, so the output stays readable. */
const q = (s: string) => (s.includes("'") || s.includes('\\') ? JSON.stringify(s) : `'${s.replace(/\\'/g, "\\'")}'`);

const FIELDS = ['title', 'detail', 'rationale', 'suggestion'] as const;

/**
 * Stable key for one finding-level template.
 *
 * A rule that emits one sentence per field gets the bare key; a rule that emits
 * several sub-cases gets a 1-based suffix in source order. Numbered rather than
 * named on purpose: a hand-assigned slug can drift from the branch it describes,
 * and the whole point of this system is that keys are derived, not curated.
 */
const findingKey = (ruleId: string, field: string, i: number, total: number) =>
  total === 1 ? `finding.${ruleId}.${field}` : `finding.${ruleId}.${field}.${i + 1}`;

const out: string[] = [];
const P = (s = '') => out.push(s);

P('/*');
P(' * GENERATED by scripts/i18n-emit-en.ts. Do not hand-edit — run the script.');
P(' *');
P(' * Key = the exact English string this build ships. Adding a key cannot change');
P(' * what an English user sees; tests/i18n.test.ts proves the key set still');
P(' * matches every user-visible string in src/.');
P(' */');
P("import type { Dictionary } from './types';");
P();
P('export const en: Dictionary = {');
P('  ui: {');
for (const k of Object.keys(UI).sort()) P(`    ${JSON.stringify(k)}: ${q(UI[k])},`);
P('  },');
P('  term: {');
for (const k of Object.keys(TERM).sort()) P(`    ${JSON.stringify(k)}: ${q(TERM[k])},`);
P('  },');
P();
P('  // ---- rule metadata: the generic rule name/rationale/suggestion ----');
P('  rule: {');
for (const id of Object.keys(d.ruleLevel).sort()) {
  const r = d.ruleLevel[id];
  P(`    ${JSON.stringify(id)}: {`);
  for (const f of ['title', 'rationale', 'suggestion'] as const) if (r[f]) P(`      ${f}: ${q(r[f])},`);
  P('    },');
}
P('  },');
P();
P('  // ---- finding-level text, one entry per emitted sentence ----');
P('  finding: {');
const keyRows: string[][] = [];
for (const id of Object.keys(d.findingLevel).sort()) {
  const f = d.findingLevel[id];
  for (const field of FIELDS) {
    const list = f[field] ?? [];
    list.forEach((text, i) => {
      const key = findingKey(id, field, i, list.length);
      P(`    ${JSON.stringify(key)}: ${q(text)},`);
      keyRows.push([key, text]);
    });
  }
}
P('  },');
P();
P('  // ---- parse-level findings (malformed file, bad encoding) ----');
P('  parse: {');
for (const code of Object.keys(d.parseFindings).sort()) {
  const p = d.parseFindings[code];
  const title = (PARSE_TITLE as Record<string, readonly [string, string]>)[code]?.[0];
  P(`    ${JSON.stringify(code)}: {`);
  P(`      message: ${q(p.message)},`);
  if (title) P(`      title: ${q(title)},`);
  P(`      rationale: ${q(PARSE_RATIONALE[0])},`);
  P(
    `      suggestion: ${q(
      code === 'ENCODING_MOJIBAKE' ? PARSE_SUGGESTION_MOJIBAKE[0] : PARSE_SUGGESTION[0],
    )},`,
  );
  if (p.detail) P(`      detail: ${q(p.detail)},`);
  P('    },');
}
P('    "_suggestion": {');
P(`      message: ${q(PARSE_SUGGESTION[0])},`);
P(`      rationale: ${q(PARSE_RATIONALE[0])},`);
P('    },');
P('  },');
P();
P('  // ---- detection assumptions ----');
P('  assumption: {');
for (const key of Object.keys(d.assumptions).sort()) {
  const a = d.assumptions[key];
  if (!a.label) continue;
  P(`    ${JSON.stringify(key)}: {`);
  for (const f of ['label', 'whenOff', 'caveat', 'evidence'] as const) if (a[f]) P(`      ${f}: ${q(a[f])},`);
  P('    },');
}
P('  },');
P();
P('  // ---- sample scenarios ----');
P('  scenario: {');
for (const id of Object.keys(d.scenarios).sort()) {
  const s = d.scenarios[id];
  if (!s.title || !s.blurb || !s.teaches) continue;
  P(`    ${JSON.stringify(id)}: {`);
  for (const f of ['title', 'blurb', 'teaches'] as const) P(`      ${f}: ${q(s[f])},`);
  P('    },');
}
P('  },');
P('};');
P();
P('export default en;');

writeFileSync('src/i18n/en.ts', out.join('\n'), 'utf8');
writeFileSync('F:/Temp/vg-finding-keys.json', JSON.stringify(Object.fromEntries(keyRows), null, 2));
console.log(
  'en.ts written |',
  Object.keys(d.ruleLevel).length, 'rules |',
  keyRows.length, 'finding slots |',
  Object.keys(d.parseFindings).length, 'parse codes |',
  Object.keys(d.assumptions).filter((k) => d.assumptions[k].label).length, 'assumptions |',
  Object.keys(d.scenarios).filter((k) => d.scenarios[k].title && d.scenarios[k].teaches).length, 'scenarios',
);
